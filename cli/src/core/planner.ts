/** §5 — level = max(framework floor, task hints, explicit), clamped by policy. */
export function inferLevel(cfg: RepoConfig, adapters: Adapter[], explicit: number | undefined, task: string | undefined): { level: Level; reasons: string[] } {
  const reasons: string[] = [];
  let l = 0;
  for (const a of adapters) { if (a.floorLevel() > l) { l = a.floorLevel(); reasons.push(`${a.id} floor=${a.floorLevel()}`); } }
  if (task) for (const [re, lv] of Object.entries(cfg.hints)) {
    if (new RegExp(re, "i").test(task) && lv > l) { l = lv; reasons.push(`task matched /${re}/ → ${lv}`); }
  }
  if (explicit !== undefined) { l = explicit; reasons.push(`explicit --level ${explicit}`); }
  const c = clampLevel(l, cfg);
  if (c !== l) reasons.push(`clamped to policy [${cfg.min_level},${cfg.max_level}] → ${c}`);
  return { level: c, reasons };
}

