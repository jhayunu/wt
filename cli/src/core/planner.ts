export function stepWorktreeAdd(ctx: Ctx, from: string): Step {
  const { rec, repoRoot } = ctx;
  let createdBranch = false;
  return {
    title: `git worktree add ${path.relative(repoRoot, rec.path)} (${rec.branch})`,
    async up(c) {
      const exists = await branchExists(c.run, repoRoot, rec.branch);
      createdBranch = !exists;
      const args = exists ? ["worktree", "add", rec.path, rec.branch] : ["worktree", "add", "-b", rec.branch, rec.path, from];
      await c.run("git", args, { cwd: repoRoot });
    },
    async down(c) {
      await c.run("git", ["worktree", "remove", "--force", rec.path], { cwd: repoRoot, allowFail: true });
      if (createdBranch) await c.run("git", ["branch", "-D", rec.branch], { cwd: repoRoot, allowFail: true });
    },
  };
}

export function mediaPathsOf(adapters: Adapter[]) { return [...new Set(adapters.flatMap((a) => a.mediaPaths()))]; }

/** nginx snippet: serve media locally if present, else proxy to main's URL. Zero filesystem coupling. */
function mediaProxyConf(ctx: Ctx, mediaPaths: string[]): string {
  const mainUrl = `https://${ctx.cfg.main}.${ctx.cfg.tld}`;
  return `# ddev-generated: no — managed by wt (media: proxy). Falls back to ${mainUrl} for media missing locally.
${mediaPaths.map((m) => `location ^~ /${m.replace(/^\/+/, "")}/ {
    try_files $uri @wt_media_main;
}`).join("\n")}
location @wt_media_main {
    # Inside the container, ${ctx.cfg.main}.${ctx.cfg.tld} would resolve to 127.0.0.1 (ourselves),
    # so go through the shared router by its network name and set the Host header instead.
    resolver 127.0.0.11 valid=30s;
    proxy_ssl_server_name on;
    proxy_ssl_name ${ctx.cfg.main}.${ctx.cfg.tld};
    proxy_ssl_verify off;
    proxy_set_header Host ${ctx.cfg.main}.${ctx.cfg.tld};
    proxy_pass https://ddev-router$request_uri;
}
`;
}

export function stepWriteConfig(ctx: Ctx, adapters: Adapter[]): Step {
  const { rec } = ctx;
  const written: string[] = [];
  return {
    title: "write .ddev/config.wt.local.yaml (+ env files)",
    async up(c) {
      const merged: Record<string, unknown> = {
        // Set the project name explicitly. DDEV merges config.*.yaml over config.yaml,
        // so this wins even when the repo pins `name:` in .ddev/config.yaml — verified
        // against DDEV v1.25.1 with `ddev utility configyaml`. Without it, a repo that
        // pins its name would register the worktree under *main's* project name.
        name: rec.name,
        ...Object.assign({}, ...adapters.map((a) => a.ddevOverrides(c))),
      };
      const mp = mediaPathsOf(adapters);
      if (rec.media !== "none" && mp.length) merged.upload_dirs = mp;
      const ddevDir = path.join(rec.path, ".ddev");
      await mkdir(ddevDir, { recursive: true });
      const header = `# generated by wt for worktree ${rec.name}; gitignored; do not edit\n`;
      const files: Record<string, string> = { ".ddev/config.wt.local.yaml": header + YAML.stringify(merged) };
      if (rec.media === "proxy" && mp.length) files[".ddev/nginx/wt-media.conf"] = mediaProxyConf(c, mp);
      for (const a of adapters) Object.assign(files, await a.envFiles(c));
      for (const [rel, content] of Object.entries(files)) {
        const p = path.join(rec.path, rel);
        if (!c.dryRun) { await mkdir(path.dirname(p), { recursive: true }); await writeFile(p, content); }
        if (!rec.createdFiles.includes(p)) rec.createdFiles.push(p);
        written.push(p);
      }
      c.log(`  files: ${written.map((x) => path.relative(rec.path, x)).join(", ")}`);
    },
    async down(c) { if (!c.dryRun) for (const f of written) await rm(f, { force: true }); },
  };
}

export function stepMedia(ctx: Ctx, adapters: Adapter[], mode: MediaStrategy = ctx.rec.media): Step | null {
  const { rec, repoRoot } = ctx;
  const mp = mediaPathsOf(adapters);
  if (!mp.length || mode === "none" || mode === "proxy") return null; // proxy is handled by the nginx snippet
  return {
    title: `media: ${mode} ${mp.join(", ")}`,
    async up(c) {
      for (const m of mp) {
        const src = path.join(repoRoot, m), dst = path.join(rec.path, m);
        if (!existsSync(src)) { c.log(`  skip ${m} (not in main)`); continue; }
        if (c.dryRun) continue;
        await rm(dst, { recursive: true, force: true });
        await mkdir(path.dirname(dst), { recursive: true });
        if (mode === "symlink") await symlink(path.relative(path.dirname(dst), src), dst);
        else await copyTree(c, src, dst);
      }
    },
    async down(c) { if (!c.dryRun) for (const m of mp) await rm(path.join(rec.path, m), { recursive: true, force: true }); },
    optional: true, // a failed media sync should not tear down a freshly cloned environment
  };
}

/** APFS clone on macOS (`cp -c`, copy-on-write, ~free), plain recursive copy elsewhere. */
async function copyTree(c: Ctx, src: string, dst: string) {
  if (process.platform === "darwin") {
    const r = await c.run("cp", ["-cR", src, dst], { allowFail: true });
    if (r.exitCode === 0) return;
  }
  await cp(src, dst, { recursive: true, force: true, dereference: false });
}

export function stepDbClone(ctx: Ctx): Step | null {
  const { rec, cfg, repoRoot } = ctx;
  if (rec.db === "seedfile") {
    const seed = path.join(repoRoot, cfg.seed.file);
    return {
      title: `db: seed file ${cfg.seed.file}`,
      async up(c) {
        if (!existsSync(seed) && !c.dryRun) throw new WtError(EXIT.GENERIC, `seed file missing: ${seed}`, "wt db seed   (refreshes it from main / ddev pull)");
      },
    };
  }
  if (rec.db !== "snapshot" && rec.db !== "dump") return null;
  return {
    title: `db: ${rec.db} from ${cfg.main}`,
    async up(c) {
      const st = await ddevStatus(c.run, cfg.main);
      if (st !== "running" && !c.dryRun) throw new WtError(EXIT.MAIN_NOT_RUNNING, `main project "${cfg.main}" is not running (status: ${st ?? "unknown"})`, `run: ddev start ${cfg.main}`);
      if (rec.db === "snapshot") {
        const snap = `wt-${rec.name}`;
        await ddev.snapshot(c.run, repoRoot, snap);
        const from = path.join(repoRoot, ".ddev", "db_snapshots"), to = path.join(rec.path, ".ddev", "db_snapshots");
        if (!c.dryRun) {
          if (!existsSync(from)) throw new WtError(EXIT.GENERIC, `snapshot dir missing: ${from}`, "did `ddev snapshot` succeed in main?");
          await mkdir(to, { recursive: true });
          // Copy only this snapshot. DDEV writes a file (`<name>-<dbtype>_<version>.gz`),
          // older versions wrote a directory — match on the first path segment so both work.
          await cp(from, to, { recursive: true, filter: (p) => p === from || path.relative(from, p).split(path.sep)[0].startsWith(snap) });
        }
        rec.snapshots.push(snap);
      } else {
        const file = path.join(rec.path, ".ddev", "wt-main.sql");
        await ddev.exportDb(c.run, repoRoot, file);
        rec.createdFiles.push(file);
      }
    },
  };
}

export function stepStart(ctx: Ctx, adapters: Adapter[]): Step {
  const { rec, cfg } = ctx;
  return {
    title: `ddev start → ${rec.url || urlFor(rec.name, cfg.tld)}`,
    async up(c) {
      await ddev.start(c.run, rec.path);
      if (rec.db === "snapshot" && rec.snapshots[0]) await ddev.snapshotRestore(c.run, rec.path, rec.snapshots[0]);
      if (rec.db === "dump") await ddev.importDb(c.run, rec.path, path.join(rec.path, ".ddev", "wt-main.sql"));
      if (rec.db === "seedfile") await ddev.importDb(c.run, rec.path, path.join(ctx.repoRoot, cfg.seed.file));
      // post-start hooks ran before the restore replaced the DB → run them once more
      if (rec.db !== "none" && rec.db !== "fresh") await ddev.start(c.run, rec.path);
      for (const a of adapters) await a.postStart(c);
      rec.prevUrl = rec.url;
    },
    async down(c) { await ddev.delete(c.run, rec.name); },
  };
}

/**
 * `git worktree add` gives you exactly what git tracks — which is not a runnable
 * checkout. Gitignored-but-required directories are missing, and at level 0/1 nothing
 * else ever writes an env file. Both failures surface far from their cause (an artisan
 * call dying inside the container), so fix them at creation.
 */
export function stepPrepareTree(ctx: Ctx, adapters: Adapter[]): Step | null {
  const { rec, repoRoot } = ctx;
  const dirs = [...new Set(adapters.flatMap((a) => a.requiredDirs?.() ?? []))];
  const shared = rec.level < 2 ? [...new Set(adapters.flatMap((a) => a.sharedFiles?.() ?? []))] : [];
  if (!dirs.length && !shared.length) return null;
  return {
    title: `prepare tree (${[...dirs, ...shared].join(", ")})`,
    async up(c) {
      if (c.dryRun) return;
      for (const d of dirs) await mkdir(path.join(rec.path, d), { recursive: true });
      for (const f of shared) {
        const src = path.join(repoRoot, f), dst = path.join(rec.path, f);
        if (!existsSync(src)) { c.log(`  skip ${f} (not in main)`); continue; }
        if (existsSync(dst)) continue;
        await cp(src, dst);
        if (!rec.createdFiles.includes(dst)) rec.createdFiles.push(dst);
      }
    },
    optional: true,
  };
}

/**
 * Level 0/1 tooling runs in *main's* container, at the worktree's path under the
 * project mount. `git worktree add` returns as soon as the host checkout is written,
 * but on a Mutagen-synced project (macOS/Windows) the container cannot see those files
 * for another few seconds — long enough that the very next `wt composer …` fails with
 * "no such file or directory". Wait for the tree to land instead of handing the agent
 * a confusing error.
 */
export function stepAwaitContainerSync(ctx: Ctx, adapters: Adapter[] = [], timeoutMs = 120_000): Step {
  const { rec, repoRoot } = ctx;
  const inContainer = path.posix.join("/var/www/html", path.relative(repoRoot, rec.path));
  // `.git` alone is not enough: it is one small file and lands before the rest of the
  // checkout, which produced "Could not open input file: artisan" seconds after wt
  // reported the worktree ready. Wait for each framework's own root file too.
  const markers = [".git", ...new Set(adapters.map((a) => a.treeMarker?.()).filter((m): m is string => !!m))];
  return {
    title: `wait for ${inContainer} to sync into main's web container`,
    async up(c) {
      if (c.dryRun) return;
      const deadline = Date.now() + timeoutMs;
      let waited = false;
      for (;;) {
        const r = await c.run("ddev", ["exec", "--dir", inContainer, "sh", "-c", markers.map((m) => `test -e '${m}'`).join(" && ")], { cwd: repoRoot, allowFail: true });
        if (r.exitCode === 0) { if (waited) c.log("  synced"); return; }
        if (Date.now() > deadline) throw new Error(`still not visible in the container after ${Math.round(timeoutMs / 1000)}s — is main running, and is this project Mutagen-synced?`);
        waited = true;
        await new Promise((res) => setTimeout(res, 2000));
      }
    },
    // A failure here means tooling will be slow to work, not that the worktree is broken.
    optional: true,
  };
}

/** Opt-in: `wt new --install`. Costs minutes on a large repo, so it is never the default. */
export function stepInstallDeps(ctx: Ctx, adapters: Adapter[]): Step | null {
  const deps = declaredDeps(adapters);
  if (!deps.length) return null;
  return {
    title: `install dependencies (${deps.map((d) => d.marker.split("/")[0]).join(", ")})`,
    async up(c) {
      if (c.dryRun) return;
      for (const d of missingDeps(c.rec, adapters)) {
        c.log(`  ${d.tool} ${d.args.join(" ")}`);
        const r = await runTool(c.run, c.repoRoot, c.rec, d.tool, d.args);
        if (r.exitCode !== 0) throw new Error(`${d.tool} ${d.args.join(" ")} failed: ${(r.stderr || r.stdout).split("\n").filter(Boolean).slice(-2).join(" ")}`);
      }
    },
    // The worktree is still usable without them; the agent just has to run the install itself.
    optional: true,
  };
}

export function stepBaseline(ctx: Ctx, providers: DbChangeProvider[]): Step {
  const { rec, cfg } = ctx;
  return {
    title: `db change-tracking baseline (${providers.map((p) => p.id).join(", ")})`,
    async up(c) {
      for (const p of providers) rec.baseline = await p.baseline(c);
      const changes = path.join(rec.path, cfg.db.changes_dir);
      if (!c.dryRun) { await mkdir(changes, { recursive: true }); if (!existsSync(path.join(changes, ".gitkeep"))) await writeFile(path.join(changes, ".gitkeep"), ""); }
    },
  };
}

/** Steps that turn an existing worktree dir into a running level-2+ environment. */
export function stepsEnvironment(ctx: Ctx, adapters: Adapter[], providers: DbChangeProvider[], start: boolean): Step[] {
  const steps: Step[] = [stepWriteConfig(ctx, adapters)];
  const m = stepMedia(ctx, adapters); if (m) steps.push(m);
  if (!start) return steps;
  const d = stepDbClone(ctx); if (d) steps.push(d);
  steps.push(stepStart(ctx, adapters), stepBaseline(ctx, providers));
  return steps;
}

