export function planNew(ctx: Ctx, adapters: Adapter[], providers: DbChangeProvider[], opts: { from: string; start: boolean; install?: boolean }): Step[] {
  const { rec } = ctx;
  const steps: Step[] = [stepWorktreeAdd(ctx, opts.from)];
  const prep = stepPrepareTree(ctx, adapters); if (prep) steps.push(prep);
  const install = opts.install ? stepInstallDeps(ctx, adapters) : null;
  if (rec.level === 0) return steps;
  if (rec.level === 1) {
    steps.push({ title: "level 1: no containers; `wt npm|composer|artisan|wp <name> …` run in main's web container", async up() {} });
    steps.push(stepAwaitContainerSync(ctx, adapters));
    // after the sync wait: the container has to see the tree before it can install into it
    if (install) steps.push(install);
    return steps;
  }
  const env = stepsEnvironment(ctx, adapters, providers, opts.start);
  // after start: `ddev composer` needs the worktree's own containers up
  return install ? [...steps, ...env, install] : [...steps, ...env];
}

/** In-place level change. Supported: 0/1→2+, 2↔3 (media swap), any→media mode change. */
export function planPromote(ctx: Ctx, adapters: Adapter[], providers: DbChangeProvider[], to: Level, media?: MediaStrategy): Step[] {
  const { rec } = ctx;
  const fromLevel = rec.level;
  const steps: Step[] = [];
  if (to === 4 || fromLevel === 4) throw new WtError(EXIT.GENERIC, "level 4 (clean) cannot be promoted to/from in place — recreate with `wt new --level 4`");
  if (to < 2 && fromLevel >= 2) throw new WtError(EXIT.GENERIC, "demoting below level 2 would delete the environment — use `wt destroy` + `wt new`");

  const targetMedia: MediaStrategy = media ?? (to >= 3 ? "copy" : to === 2 ? (rec.media === "copy" ? "symlink" : rec.media) : rec.media);

  if (fromLevel < 2 && to >= 2) {
    rec.level = to; rec.media = targetMedia; rec.db = ctx.cfg.defaults.db; rec.url = urlFor(rec.name, ctx.cfg.tld);
    return stepsEnvironment(ctx, adapters, providers, true);
  }

  // level ≥ 2 already: only media may change
  if (targetMedia !== rec.media) {
    const prev = rec.media;
    steps.push({
      title: `media: ${prev} → ${targetMedia}`,
      async up(c) {
        rec.media = targetMedia;
        if (prev === "proxy" || targetMedia === "proxy") await stepWriteConfig(c, adapters).up(c); // (re)write nginx snippet + config
        if (prev === "proxy" && targetMedia !== "proxy" && !c.dryRun) await rm(path.join(rec.path, ".ddev", "nginx", "wt-media.conf"), { force: true });
        const m = stepMedia(c, adapters, targetMedia);
        if (m) await m.up(c);
        else if (targetMedia === "proxy" || targetMedia === "none") for (const p of mediaPathsOf(adapters)) {
          const dst = path.join(rec.path, p);
          if (!c.dryRun && existsSync(dst)) { const st = await lstat(dst); if (st.isSymbolicLink() || targetMedia === "none") await rm(dst, { recursive: true, force: true }); }
        }
        if (prev === "proxy" || targetMedia === "proxy") await c.run("ddev", ["restart"], { cwd: rec.path });
      },
      async down() { rec.media = prev; },
    });
  }
  steps.push({ title: `level ${fromLevel} → ${to}`, async up() { rec.level = to; } });
  return steps;
}

/** Claim a warm-pool entry: rename dir/project, switch branch, rewrite URLs. Much faster than a fresh clone. */
export function planPoolClaim(ctx: Ctx, adapters: Adapter[], providers: DbChangeProvider[], poolRec: { name: string; path: string; url: string; snapshots: string[] }, from: string): Step[] {
  const { rec, repoRoot } = ctx;
  // DDEV names the database volume after the project, so `ddev delete` below takes the
  // pooled database with it — the very thing the pool exists to have ready. Snapshot it
  // first: the file lands in <path>/.ddev/db_snapshots, travels with `git worktree move`,
  // and is restored into the renamed project after it starts. Same mechanism as
  // stepDbClone, which is verified against real DDEV.
  const claimSnap = `wt-claim-${rec.name}`;
  return [
    {
      title: `claim pool entry ${poolRec.name} → ${rec.name}`,
      async up(c) {
        await ddev.snapshot(c.run, poolRec.path, claimSnap);
        await ddev.stop(c.run, poolRec.name);
        await ddev.delete(c.run, poolRec.name); // drops the registry entry for the old name; containers and the db volume are recreated under the new one
        await c.run("git", ["worktree", "move", poolRec.path, rec.path], { cwd: repoRoot });
        const exists = await branchExists(c.run, repoRoot, rec.branch);
        const poolBranch = (await c.run("git", ["rev-parse", "--abbrev-ref", "HEAD"], { cwd: rec.path, allowFail: true })).stdout.trim();
        await c.run("git", exists ? ["checkout", rec.branch] : ["checkout", "-b", rec.branch, from], { cwd: rec.path });
        if (poolBranch.startsWith("wt/")) await c.run("git", ["branch", "-D", poolBranch], { cwd: repoRoot, allowFail: true });
        rec.prevUrl = poolRec.url; // DB still references the pool hostname; adapters rewrite prevUrl → url
        rec.snapshots = [];
        // The renamed project must not reuse router/cert config generated for the old name (learned from workspace-manager).
        if (!c.dryRun) await rm(path.join(rec.path, ".ddev", "traefik"), { recursive: true, force: true });
      },
      async down(c) {
        // Moving back is pointless: `up` deleted the pool project irreversibly and the
        // entry has already been struck from the manifest, so there is no pool entry to
        // restore. Clear the debris instead of leaving a half-renamed worktree that makes
        // the next claim fail with "path exists".
        for (const p of [rec.path, poolRec.path]) {
          await c.run("git", ["worktree", "remove", "--force", p], { cwd: repoRoot, allowFail: true });
          if (!c.dryRun) await rm(p, { recursive: true, force: true });
        }
        await c.run("git", ["worktree", "prune"], { cwd: repoRoot, allowFail: true });
      },
    },
    stepWriteConfig(ctx, adapters),
    {
      title: `ddev start → ${rec.url} (URL fixup from ${poolRec.url})`,
      async up(c) {
        await ddev.start(c.run, rec.path);
        await ddev.snapshotRestore(c.run, rec.path, claimSnap);
        // post-start hooks ran against the empty database the new volume started with,
        // so run them again now the pooled data is back — this is what rewrites
        // poolRec.url to rec.url
        await ddev.start(c.run, rec.path);
        for (const a of adapters) await a.postStart(c);
        await ddev.snapshot(c.run, rec.path, `wt-${rec.name}`); rec.snapshots.push(`wt-${rec.name}`);
        rec.prevUrl = rec.url;
      },
      async down(c) { await ddev.delete(c.run, rec.name); },
    },
    stepBaseline(ctx, providers),
  ];
}

export function planDestroy(ctx: Ctx, keepBranch: boolean): Step[] {
  const { rec, repoRoot } = ctx;
  return [
    { title: `ddev delete ${rec.name} (snapshots too)`, async up(c) { if (rec.level >= 2) await ddev.delete(c.run, rec.name); } },
    { title: "remove generated files", async up(c) { if (!c.dryRun) for (const f of rec.createdFiles) await rm(f, { force: true }).catch(() => {}); } },
    { title: "remove baseline", async up(c) { if (!c.dryRun) await rm(path.join(repoRoot, ".wt", "baseline", rec.name), { recursive: true, force: true }); } },
    {
      // Destroy has to be idempotent. A worktree whose directory is already gone — removed by
      // hand, or by an earlier destroy that died after this step — would otherwise fail here,
      // and because the caller only strikes the manifest entry once every step succeeds, the
      // record would survive and keep counting against max_concurrent forever.
      title: `git worktree remove ${path.relative(repoRoot, rec.path)}`,
      async up(c) {
        const alreadyGone = !c.dryRun && !existsSync(rec.path);
        await c.run("git", ["worktree", "remove", "--force", rec.path], { cwd: repoRoot, allowFail: alreadyGone });
        // Drops the stale .git/worktrees admin entry a vanished directory leaves behind.
        if (alreadyGone) await c.run("git", ["worktree", "prune"], { cwd: repoRoot, allowFail: true });
      },
    },
    ...(keepBranch ? [] : [{ title: `git branch -D ${rec.branch}`, async up(c: Ctx) { await c.run("git", ["branch", "-D", rec.branch], { cwd: repoRoot, allowFail: true }); } }]),
  ];
}

